import {
  ForbiddenException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { Registry, Counter } from 'prom-client';
import { AnalyticsEventDto } from './dto/analytics-event.dto';
import { DiscoveryRequestDto } from './dto/discovery-request.dto';
import { PaginationQueryDto } from './dto/pagination-query.dto';

const tenantKey = (sellerId: string, storeId: string) =>
  `${sellerId}:${storeId}`;

@Injectable()
export class PlatformService {
  private readonly products = new Map([
    [
      tenantKey('seller_demo', 'store_wysh'),
      [
        {
          id: 'p-1',
          title: 'Wysh Portable Blender',
          sku: 'WB-100',
          status: 'ACTIVE',
          price: 2499,
          inventory: 128,
        },
        {
          id: 'p-2',
          title: 'Wysh Cold Brew Bottle',
          sku: 'WB-101',
          status: 'DRAFT',
          price: 1299,
          inventory: 45,
        },
        {
          id: 'p-3',
          title: 'Wysh Travel Kettle',
          sku: 'WB-102',
          status: 'ACTIVE',
          price: 3199,
          inventory: 68,
        },
      ],
    ],
  ]);

  private readonly offers = [
    {
      id: 'offer-1',
      productId: 'canonical-1',
      platform: 'Amazon',
      price: 2399,
      discount: '20% off',
      affiliateUrl: 'https://example.com/amazon/offer-1',
      confidence: 0.98,
      availability: 'In stock',
      eta: 'Tomorrow',
    },
    {
      id: 'offer-2',
      productId: 'canonical-1',
      platform: 'Flipkart',
      price: 2449,
      discount: '18% off',
      affiliateUrl: 'https://example.com/flipkart/offer-2',
      confidence: 0.94,
      availability: 'In stock',
      eta: '2 days',
    },
  ];

  private readonly analyticsDeduplication = new Set<string>();
  private readonly registry = new Registry();
  private readonly analyticsCounter = new Counter({
    name: 'wysh_analytics_events_total',
    help: 'Number of analytics events accepted by the API',
    registers: [this.registry],
    labelNames: ['eventType'],
  });
  private readonly redirectCounter = new Counter({
    name: 'wysh_redirect_clicks_total',
    help: 'Number of affiliate redirects generated by the API',
    registers: [this.registry],
    labelNames: ['platform'],
  });

  getLiveness() {
    return { status: 'ok', service: 'wysh-sellers-api' };
  }

  getReadiness() {
    return {
      status: 'ok',
      checks: {
        postgres: 'configured-via-infra',
        redis: 'configured-via-infra',
        minio: 'configured-via-infra',
      },
    };
  }

  checkSlugAvailability(slug: string) {
    return {
      slug,
      available: !['wysh', 'admin', 'seller'].includes(slug.toLowerCase()),
    };
  }

  getDashboardSummary(sellerId: string, storeId: string) {
    return {
      tenant: { sellerId, storeId },
      widgets: {
        revenue: 680000,
        orders: 1247,
        payouts: 210000,
        pendingShipments: 142,
      },
      topProducts: this.products.get(tenantKey(sellerId, storeId)) ?? [],
    };
  }

  listProducts(sellerId: string, storeId: string, query: PaginationQueryDto) {
    const scopedProducts =
      this.products.get(tenantKey(sellerId, storeId)) ?? [];
    const filtered = scopedProducts.filter(
      (product) =>
        product.title.toLowerCase().includes(query.search.toLowerCase()) ||
        product.sku.toLowerCase().includes(query.search.toLowerCase()),
    );

    return {
      data: filtered.slice(
        (query.page - 1) * query.pageSize,
        query.page * query.pageSize,
      ),
      total: filtered.length,
      page: query.page,
      pageSize: query.pageSize,
    };
  }

  ingestAnalytics(
    payload: AnalyticsEventDto,
    sellerId?: string,
    storeId?: string,
  ) {
    if (
      payload.idempotencyKey &&
      this.analyticsDeduplication.has(payload.idempotencyKey)
    ) {
      return { accepted: true, deduplicated: true };
    }

    if (payload.idempotencyKey) {
      this.analyticsDeduplication.add(payload.idempotencyKey);
    }

    this.analyticsCounter.inc({ eventType: payload.eventType });

    return {
      accepted: true,
      sellerId,
      storeId,
      eventType: payload.eventType,
    };
  }

  discover(payload: DiscoveryRequestDto) {
    return {
      mode: payload.mode,
      query: payload.query,
      canonicalProduct: {
        id: 'canonical-1',
        title: 'Wysh Portable Blender',
        matchingType:
          payload.mode === 'url'
            ? 'EXACT'
            : payload.mode === 'image'
              ? 'VISUAL'
              : 'SEMANTIC',
        confidence:
          payload.mode === 'url'
            ? 0.98
            : payload.mode === 'image'
              ? 0.92
              : 0.88,
      },
      offers: this.offers,
    };
  }

  getRedirect(offerId: string) {
    const offer = this.offers.find((entry) => entry.id === offerId);
    if (!offer) {
      throw new NotFoundException('Offer not found.');
    }

    this.redirectCounter.inc({ platform: offer.platform });
    return offer.affiliateUrl;
  }

  async getMetrics() {
    return {
      contentType: this.registry.contentType,
      body: await this.registry.metrics(),
    };
  }

  ensureTenantAccess(
    userSellerId: string,
    userStoreId: string,
    sellerId: string,
    storeId: string,
  ) {
    if (userSellerId !== sellerId || userStoreId !== storeId) {
      throw new ForbiddenException('Cross-tenant access attempt rejected.');
    }
  }
}

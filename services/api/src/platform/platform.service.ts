  listProducts(sellerId: string, storeId: string, query: PaginationQueryDto) {
    const scopedProducts =
      this.products.get(tenantKey(sellerId, storeId)) ?? [];
    const filtered = scopedProducts.filter(
      (product) =>
        product.title.toLowerCase().includes(query.search.toLowerCase()) ||
        product.sku.toLowerCase().includes(query.search.toLowerCase()),
    );

    return {
      data: filtered.slice(
        (query.page - 1) * query.pageSize,
        query.page * query.pageSize,
      ),
      total: filtered.length,
      page: query.page,
      pageSize: query.pageSize,
    };
  }

  createProduct(sellerId: string, storeId: string, dto: CreateProductDto) {
    const key = tenantKey(sellerId, storeId);
    const existingProducts = this.products.get(key) ?? [];

    const newProduct = {
      id: `p-${Date.now()}`,
      title: dto.title,
      sku: dto.sku,
      brand: dto.brand,
      status: dto.status,
      price: dto.price,
      inventory: dto.inventory,
      imageUrl: dto.imageUrl,
    };

    const updatedProducts = [...existingProducts, newProduct];
    this.products.set(key, updatedProducts);

    return newProduct;
  }

  updateProduct(
    sellerId: string,
    storeId: string,
    productId: string,
    dto: UpdateProductDto,
  ) {
    const key = tenantKey(sellerId, storeId);
    const existingProducts = this.products.get(key) ?? [];

    const productIndex = existingProducts.findIndex((p) => p.id === productId);

    if (productIndex === -1) {
      throw new NotFoundException('Product not found.');
    }

    const updatedProduct = {
      ...existingProducts[productIndex],
      ...dto,
      id: existingProducts[productIndex].id,
    };

    const updatedProducts = [...existingProducts];
    updatedProducts[productIndex] = updatedProduct;
    this.products.set(key, updatedProducts);

    return updatedProduct;
  }

  deleteProduct(sellerId: string, storeId: string, productId: string) {
    const key = tenantKey(sellerId, storeId);
    const existingProducts = this.products.get(key) ?? [];

    const productIndex = existingProducts.findIndex((p) => p.id === productId);

    if (productIndex === -1) {
      throw new NotFoundException('Product not found.');
    }

    const deletedProduct = existingProducts[productIndex];
    const remainingProducts = [
      ...existingProducts.slice(0, productIndex),
      ...existingProducts.slice(productIndex + 1),
    ];
    this.products.set(key, remainingProducts);

    return deletedProduct;
  }

  createOrder(sellerId: string, storeId: string, dto: CreateOrderDto) {
    const key = tenantKey(sellerId, storeId);
    const existingOrders = this.orders.get(key) ?? [];

    const newOrder = {
      id: `ord-${Date.now()}`,
      productId: dto.productId,
      quantity: dto.quantity,
      status: OrderStatus.NEW,
      sellerId,
      storeId,
      createdAt: Date.now(),
    };

    const updatedOrders = [...existingOrders, newOrder];
    this.orders.set(key, updatedOrders);

    return newOrder;
  }

  updateOrderStatus(
    sellerId: string,
    storeId: string,
    orderId: string,
    dto: UpdateOrderStatusDto,
  ) {
    const key = tenantKey(sellerId, storeId);
    const existingOrders = this.orders.get(key) ?? [];

    const order = existingOrders.find((o) => o.id === orderId);

    if (!order) {
      throw new NotFoundException('Order not found.');
    }

    // Validate state transition
    const statusTransitions: Record<OrderStatus, OrderStatus[]> = {
      [OrderStatus.NEW]: [OrderStatus.CONFIRMED],
      [OrderStatus.CONFIRMED]: [OrderStatus.PACKED],
      [OrderStatus.PACKED]: [OrderStatus.SHIPPED],
      [OrderStatus.SHIPPED]: [OrderStatus.DELIVERED],
      [OrderStatus.DELIVERED]: [],
    };

    const allowedNextStatuses = statusTransitions[order.status];
    if (allowedNextStatuses && !allowedNextStatuses.includes(dto.status)) {
      throw new ForbiddenException(
        `Invalid state transition from ${order.status} to ${dto.status}.`,
      );
    }

    order.status = dto.status;
    if (dto.carrier) order.carrier = dto.carrier;
    if (dto.trackingNumber) order.trackingNumber = dto.trackingNumber;

    const updatedOrders = [...existingOrders];
    const orderIndex = updatedOrders.findIndex((o) => o.id === orderId);
    updatedOrders[orderIndex] = order;
    this.orders.set(key, updatedOrders);

    return order;
  }

